const _buildGrid = (entries) => {
  const grid = Array.from({ length: 5 }, () => Array.from({ length: 8 }, () => []));
  let ei = 0;
  for (let day = 0; day < 5; day++) {
    for (let slot = 0; slot < 8; slot++) {
      if (slot === 4) continue; // lunch
      if (ei < entries.length) { grid[day][slot] = [entries[ei % entries.length]]; ei++; }
    }
  }
  return grid;
};

