/* Hash a subject code into a stable color from the brand palette */
const SUBJECT_PALETTE = [
  { fg: T.accent, bg: T.accentSoft, border: T.accentBorder },
  { fg: T.blue,   bg: T.blueSoft,   border: 'rgba(59,130,246,0.25)' },
  { fg: T.green,  bg: T.greenSoft,  border: 'rgba(16,185,129,0.25)' },
  { fg: T.amber,  bg: T.amberSoft,  border: 'rgba(245,158,11,0.25)' },
  { fg: '#ec4899', bg: '#fce7f3',   border: 'rgba(236,72,153,0.25)' },
  { fg: '#06b6d4', bg: '#cffafe',   border: 'rgba(6,182,212,0.25)' },
  { fg: '#f97316', bg: '#ffedd5',   border: 'rgba(249,115,22,0.25)' },
  { fg: '#84cc16', bg: '#ecfccb',   border: 'rgba(132,204,22,0.25)' },
];
export const subjectColor = (code = '') => {
  let hash = 0;
  for (let i = 0; i < code.length; i++) hash = (hash * 31 + code.charCodeAt(i)) | 0;
  return SUBJECT_PALETTE[Math.abs(hash) % SUBJECT_PALETTE.length];
};

