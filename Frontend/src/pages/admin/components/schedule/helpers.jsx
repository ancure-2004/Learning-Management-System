const _demoGet  = () => { try { const r = localStorage.getItem(DEMO_KEY); if (r) return JSON.parse(r); } catch {} localStorage.setItem(DEMO_KEY, JSON.stringify(DEMO_SEED)); return JSON.parse(JSON.stringify(DEMO_SEED)); };
const _demoSet  = (all) => localStorage.setItem(DEMO_KEY, JSON.stringify(all));
export const getDemoTimetables  = ()       => _demoGet();
export const getDemoTimetable   = (id)     => _demoGet().find(t => t._id === id) || null;
export const deleteDemoTT       = (id)     => { _demoSet(_demoGet().filter(t => t._id !== id)); };
export const publishDemoTT      = (id)     => { const all = _demoGet(); const t = all.find(x => x._id === id); if (t) { t.status = 'published'; _demoSet(all); } };
export const saveDemoEdit       = (id, schedule, desc = 'Manual edits') => {
  const all = _demoGet(); const tt = all.find(t => t._id === id); if (!tt) return null;
  const v = tt.currentVersion + 1;
  tt.history.push({ versionNumber: v, changeDescription: desc, timestamp: new Date().toISOString(), editedBy: { firstName: 'Admin', lastName: '' } });
  tt.currentVersion = v; tt.schedule = schedule; _demoSet(all); return JSON.parse(JSON.stringify(tt));
};
export const revertDemoVersion  = (id, vn) => {
  const all = _demoGet(); const tt = all.find(t => t._id === id); if (!tt) return null;
  const v = tt.currentVersion + 1;
  tt.history.push({ versionNumber: v, changeDescription: `Reverted to v${vn}`, timestamp: new Date().toISOString(), editedBy: { firstName: 'Admin', lastName: '' } });
  tt.currentVersion = v; _demoSet(all); return JSON.parse(JSON.stringify(tt));
};
